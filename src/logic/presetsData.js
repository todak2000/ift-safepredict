export function formatThroatRadius(rcMeters) {
  if (!rcMeters || rcMeters <= 0) return '—';
  const rcUm = rcMeters * 1e6;
  if (rcUm < 0.1) {
    const rcNm = rcMeters * 1e9;
    return `${rcNm.toFixed(1)} nm (${rcUm.toFixed(4)} µm)`;
  }
  return `${rcUm.toPrecision(3)} µm`;
}
