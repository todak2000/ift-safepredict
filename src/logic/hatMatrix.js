const MATRICES = { sub: XTX_INV_SUB, sup: XTX_INV_SUP };

/**
 * Compute Williams-Plot leverage score for a query point.
 *
 * @param {object} scaled — MinMax-scaled features with keys:
 *   Pr, Tr, MCM, BCM, x_CH4, x_N2, drho_sq, BCM_bin, CH4_bin, N2_bin
 * @param {'sub'|'sup'} regime
 * @returns {number} leverage h (dimensionless)
 */
export const computeLeverage = (scaled, regime) => {
  const M = MATRICES[regime];
  // Assemble 11-element query vector [intercept, ...features]
  const x = [
    1,
    scaled.Pr, scaled.Tr, scaled.MCM, scaled.BCM,
    scaled.x_CH4, scaled.x_N2, scaled.drho_sq,
    scaled.BCM_bin, scaled.CH4_bin, scaled.N2_bin,
  ];
  // h = x^T (X^T X)^{-1} x
  let h = 0;
  for (let i = 0; i < 11; i++) {
    let row_sum = 0;
    for (let j = 0; j < 11; j++) {
      row_sum += M[i][j] * x[j];
    }
    h += x[i] * row_sum;
  }
  return h;
};
